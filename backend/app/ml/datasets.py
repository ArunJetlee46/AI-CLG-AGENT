"""Datasets for the four Phase-9 prediction tasks.

Three data sources:
  performance / attendance  -> observed data (synthetic generator populated DB)
  placement / dropout       -> OBSERVED features + SIMULATED labels

The simulated labels are generated by explicit, documented committee rules plus
seeded noise (np.random.default_rng) - they stand in for ground truth that does
not exist in the system yet. When real placement/dropout records arrive, swap
`_synthetic_*` for the observed labels without touching the feature layer.
"""
import logging
import time

import numpy as np
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.ml.features import _grade_to_score
from app.models.entities import AttendanceRecord, Course, Enrollment, Result, Student

logger = logging.getLogger(__name__)

TASKS = ["performance", "placement", "attendance", "dropout"]
SEED = 42
ATTENDANCE_RISK_THRESHOLD = 0.6
MIN_WEEKS_FOR_ATTENDANCE = 8

DATASET_CACHE_TTL_SECONDS = 300.0
_dataset_cache: dict = {"built_at": 0.0, "data": None}


def _logistic(z: float) -> float:
    return 1.0 / (1.0 + np.exp(-max(-30.0, min(30.0, z))))


def _program_boost(program: str) -> float:
    return 0.15 if program in ("Computer Science", "Engineering", "Business") else 0.0


# ---------------------------------------------------------------------------
# Shared student base
# ---------------------------------------------------------------------------


def _student_base(db: Session) -> list[dict]:
    """One record per student with aggregates used by all four tasks."""
    rows: list[dict] = []
    students = db.execute(select(Student)).scalars().all()
    for student in students:
        enrollments = db.execute(
            select(Enrollment).where(Enrollment.student_id == student.id, Enrollment.status == "approved")
        ).scalars().all()
        if not enrollments:
            continue
        attendance_sum = 0.0
        attendance_n = 0
        marks_sum = 0.0
        marks_n = 0
        credits = 0
        for enrollment in enrollments:
            present = db.execute(
                select(func.count(AttendanceRecord.id)).where(
                    AttendanceRecord.enrollment_id == enrollment.id, AttendanceRecord.status == "present"
                )
            ).scalar_one()
            total = db.execute(
                select(func.count(AttendanceRecord.id)).where(AttendanceRecord.enrollment_id == enrollment.id)
            ).scalar_one()
            attendance_sum += present / total if total else 0.5
            attendance_n += 1
            result = db.execute(select(Result).where(Result.enrollment_id == enrollment.id)).scalar_one_or_none()
            if result is not None:
                marks_sum += result.marks
                marks_n += 1
            course = db.execute(select(Course).where(Course.id == enrollment.course_id)).scalar_one_or_none()
            credits += course.credits if course else 0
        rows.append(
            {
                "student_id": student.student_id,
                "student_uuid": student.id,
                "year": student.year,
                "program": student.program,
                "gpa": float(student.gpa or 0.0),
                "attendance_rate": attendance_sum / attendance_n,
                "avg_marks": (marks_sum / marks_n) if marks_n else 0.0,
                "course_load": len(enrollments),
                "credits": credits,
            }
        )
    return rows


def _one_hot(rows: list[dict], key: str) -> tuple[list[np.ndarray], list[str]]:
    values = sorted({r[key] for r in rows if r[key]})
    cols = [f"{key}_{v}" for v in values]
    enc = []
    for r in rows:
        vec = np.zeros(len(values))
        if r[key] in values:
            vec[values.index(r[key])] = 1.0
        enc.append(vec)
    return enc, cols


# ---------------------------------------------------------------------------
# Task 1 - Student Performance (pass/fail, enrollment-level, observed label)
# ---------------------------------------------------------------------------


def build_performance_dataset(db: Session, seed: int = SEED) -> dict:
    rows: list[dict] = []
    ids: list[dict] = []
    enrollments = db.execute(
        select(Enrollment).where(Enrollment.status == "approved")
    ).scalars().all()
    for enrollment in enrollments:
        student = db.execute(select(Student).where(Student.id == enrollment.student_id)).scalar_one_or_none()
        course = db.execute(select(Course).where(Course.id == enrollment.course_id)).scalar_one_or_none()
        if student is None or course is None:
            continue
        present = db.execute(
            select(func.count(AttendanceRecord.id)).where(
                AttendanceRecord.enrollment_id == enrollment.id, AttendanceRecord.status == "present"
            )
        ).scalar_one()
        total = db.execute(
            select(func.count(AttendanceRecord.id)).where(AttendanceRecord.enrollment_id == enrollment.id)
        ).scalar_one()
        result = db.execute(select(Result).where(Result.enrollment_id == enrollment.id)).scalar_one_or_none()
        rows.append(
            {
                "gpa": float(student.gpa or 0.0),
                "attendance_rate": present / total if total else 0.5,
                "prior_grade": _grade_to_score(result.grade) if result else 0.5,
                "year": student.year,
                "credits": course.credits,
                "course_load": 1,
                "program": student.program,
                "dept": course.department,
                "label": 1 if result and result.grade != "F" else 0,
            }
        )
        ids.append({"student_id": student.student_id, "course_code": course.code})
    return _assemble(rows, ids, "performance",
                     "label: pass = final grade != F (observed Result rows)")


# ---------------------------------------------------------------------------
# Task 2 - Attendance risk (student-level, observed weekly series)
# ---------------------------------------------------------------------------


def build_attendance_dataset(db: Session, seed: int = SEED) -> dict:
    students = db.execute(select(Student)).scalars().all()
    rows: list[dict] = []
    ids: list[dict] = []
    for student in students:
        records = db.execute(
            select(AttendanceRecord, Enrollment)
            .join(Enrollment, AttendanceRecord.enrollment_id == Enrollment.id)
            .where(Enrollment.student_id == student.id)
            .order_by(AttendanceRecord.day)
        ).all()
        if not records:
            continue
        week_of = [(r.day - records[0][0].day).days // 7 for r, _ in records]
        n_weeks = max(week_of) + 1
        if n_weeks < MIN_WEEKS_FOR_ATTENDANCE:
            continue
        weekly = [0.0] * n_weeks
        counts = [0] * n_weeks
        for (record, _), week in zip(records, week_of):
            counts[week] += 1
            if record.status == "present":
                weekly[week] += 1
        rates = np.array([weekly[w] / counts[w] if counts[w] else 0.5 for w in range(n_weeks)])

        horizon = max(1, int(round(n_weeks * 0.4)))
        known, future = rates[:-horizon], rates[-horizon:]
        if len(known) < 3:
            continue
        # feature: mean, trend, variability over the known window
        slope = float(np.polyfit(np.arange(len(known)), known, 1)[0])
        label = 1 if future.mean() < ATTENDANCE_RISK_THRESHOLD else 0
        rows.append(
            {
                "attendance_mean": float(known.mean()),
                "attendance_trend": slope,
                "attendance_volatility": float(known.std()),
                "gpa": float(student.gpa or 0.0),
                "year": student.year,
                "program": student.program,
                "course_load": 1,
                "label": label,
            }
        )
        ids.append({"student_id": student.student_id, "course_code": None})
    return _assemble(rows, ids, "attendance",
                     f"label: mean attendance over last 40% of weeks < {ATTENDANCE_RISK_THRESHOLD} "
                     "(observed AttendanceRecord series; temporal train/test split)")


# ---------------------------------------------------------------------------
# Task 3 - Placement readiness (SIMULATED label - documented rule)
# ---------------------------------------------------------------------------


def build_placement_dataset(db: Session, seed: int = SEED) -> dict:
    rows: list[dict] = []
    ids: list[dict] = []
    rng = np.random.default_rng(seed)
    for base in _student_base(db):
        score = (
            3.0 * (base["gpa"] / 4.0)
            + 2.5 * base["attendance_rate"]
            + 1.2 * _program_boost(base["program"])
            + 0.3 * (base["avg_marks"] / 100.0)
            - 3.0
        )
        label = 1 if _logistic(score) > rng.random() else 0
        rows.append(
            {
                "gpa": base["gpa"],
                "attendance_rate": base["attendance_rate"],
                "avg_marks": base["avg_marks"],
                "year": base["year"],
                "course_load": base["course_load"],
                "credits": base["credits"],
                "program": base["program"],
                "label": label,
            }
        )
        ids.append({"student_id": base["student_id"], "course_code": None})
    return _assemble(rows, ids, "placement",
                     "SIMULATED label: placement committee rule v1 "
                     "(3.0*gpa + 2.5*att + 1.2*program boost - 3.0) + seeded noise")


# ---------------------------------------------------------------------------
# Task 4 - Dropout risk (SIMULATED label - documented rule)
# ---------------------------------------------------------------------------


def build_dropout_dataset(db: Session, seed: int = SEED) -> dict:
    rows: list[dict] = []
    ids: list[dict] = []
    rng = np.random.default_rng(seed + 1)
    for base in _student_base(db):
        score = (
            2.4 * (1.0 - base["attendance_rate"])
            + 2.0 * (1.0 - base["gpa"] / 4.0)
            + 0.8 * (1.0 if base["year"] == 1 else 0.0)
            - 3.6
        )
        label = 1 if _logistic(score) > rng.random() else 0
        rows.append(
            {
                "gpa": base["gpa"],
                "attendance_rate": base["attendance_rate"],
                "avg_marks": base["avg_marks"],
                "year": base["year"],
                "course_load": base["course_load"],
                "credits": base["credits"],
                "program": base["program"],
                "label": label,
            }
        )
        ids.append({"student_id": base["student_id"], "course_code": None})
    return _assemble(rows, ids, "dropout",
                     "SIMULATED label: retention committee rule v1 "
                     "(2.4*(1-att) + 2.0*(1-gpa/4) + 0.8*freshman - 3.6) + seeded noise")


# ---------------------------------------------------------------------------
# Assembly
# ---------------------------------------------------------------------------


def _assemble(rows: list[dict], ids: list[dict], task: str, target_note: str) -> dict:
    if not rows:
        return {"task": task, "rows": 0, "X": np.zeros((0, 0)), "y": np.zeros(0, dtype=int),
                "features": [], "ids": [], "meta": {"task": task, "target_note": target_note, "rows": 0}}
    program_enc, program_cols = _one_hot(rows, "program")
    dept_cols: list[str] = []
    dept_enc: list[np.ndarray] | None = None
    if "dept" in rows[0]:
        dept_enc, dept_cols = _one_hot(rows, "dept")
    base_features = [k for k in rows[0] if k not in ("label", "program", "dept")]
    features = base_features + program_cols + dept_cols
    X = np.zeros((len(rows), len(features)))
    for i, r in enumerate(rows):
        vec = [float(r[k]) for k in base_features] + list(program_enc[i])
        if dept_enc is not None:
            vec += list(dept_enc[i])
        X[i] = vec
    y = np.array([r["label"] for r in rows], dtype=int)
    return {
        "task": task,
        "rows": len(rows),
        "X": X,
        "y": y,
        "features": features,
        "ids": ids,
        "meta": {
            "task": task,
            "target_note": target_note,
            "rows": len(rows),
            "pos_rate": round(float(y.mean()), 4),
        },
    }


def build_all(db: Session, seed: int = SEED, *, use_cache: bool = True) -> dict[str, dict]:
    """Build all four task datasets.

    Building is N+1-query heavy against SQLite (see load-test findings in
    PHASE12), so results are cached for DATASET_CACHE_TTL_SECONDS. The datasets
    change only when synthetic data is (re)generated; call
    invalidate_dataset_cache() from the generation paths. Pass use_cache=False
    when the caller needs a fresh snapshot.
    """
    global _dataset_cache
    cached = _dataset_cache["data"]
    if use_cache and cached is not None and time.time() - _dataset_cache["built_at"] < DATASET_CACHE_TTL_SECONDS:
        return cached
    data = {
        task: builder(db, seed)
        for task, builder in (
            ("performance", build_performance_dataset),
            ("attendance", build_attendance_dataset),
            ("placement", build_placement_dataset),
            ("dropout", build_dropout_dataset),
        )
    }
    if use_cache:
        _dataset_cache = {"built_at": time.time(), "data": data}
    return data


def invalidate_dataset_cache() -> None:
    """Drop the cached dataset snapshot (call after synthetic data changes)."""
    global _dataset_cache
    _dataset_cache = {"built_at": 0.0, "data": None}
